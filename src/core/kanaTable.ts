const kanaIndex = new Map<string, string[]>()
for (const [kana_, romaji_] of KANA_TO_ROMAJI) {
  const list = kanaIndex.get(kana_)
  if (list) list.push(romaji_)
  else kanaIndex.set(kana_, [romaji_])
}

const romajiIndex = new Map<string, (readonly [string, string])[]>()
for (const pair of ROMAJI_TO_KANA) {
  const list = romajiIndex.get(pair[1])
  if (list) list.push(pair)
  else romajiIndex.set(pair[1], [pair])
}

const EMPTY: readonly (readonly [string, string])[] = []

/** agi::kana_to_romaji：精确匹配假名（1–2 字符），按源码顺序返回罗马字 */
export function kanaToRomaji(kana: string): string[] {
  return kanaIndex.get(kana) ?? []
}

/** agi::romaji_to_kana：取 romaji 最长的 1–3 字符前缀，返回其全部假名候选 */
export function romajiToKana(romaji: string): readonly (readonly [string, string])[] {
  for (let len = Math.min(3, romaji.length); len > 0; len--) {
    const entries = romajiIndex.get(romaji.slice(0, len))
    if (entries) return entries
  }
  return EMPTY
}
